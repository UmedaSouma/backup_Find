#include "manager_number.h"

//===========================================================================================================
// コンストラクタ
//===========================================================================================================
CManagerNumber::CManagerNumber():
	m_pTimer(nullptr)
{
}

//===========================================================================================================
// デストラクタ
//===========================================================================================================
CManagerNumber::~CManagerNumber()
{
}

//===========================================================================================================
// 初期化処理
//===========================================================================================================
void CManagerNumber::Init()
{
	if (m_pTimer == nullptr)
	{
		m_pTimer = new CTimer;

		m_pTimer->Init();
	}
}

//===========================================================================================================
// 終了処理
//===========================================================================================================
void CManagerNumber::Uninit()
{
	if (m_pTimer != nullptr)
	{
		m_pTimer->Uninit();
		m_pTimer = nullptr;
	}
}

//===========================================================================================================
// 更新処理
//===========================================================================================================
void CManagerNumber::Update()
{
	if (m_pTimer != nullptr)
	{
		m_pTimer->Update();
	}
}

//===========================================================================================================
// 描画処理
//===========================================================================================================
void CManagerNumber::Draw()
{
	if (m_pTimer != nullptr)
	{
		m_pTimer->Draw();
	}
}
