#ifndef _PARTICLE_H_
#define _PARTICLE_H_
#include "main.h"
#include "effect.h"

class CParticle :public CEffect
{
public:
	// パーティクルの種類
	typedef enum
	{
		PARTICLE_SPARK=0,
		PARTICLE_MAX
	}PARTICLE_TYPE;

	CParticle();
	~CParticle()override;
	HRESULT Init()override;	// 初期設定
	void Uninit()override;	// 終了
	void Update()override;	// 更新
	void Draw()override;	// 描画

	static CParticle* Create();   // 生成処理
private:
	D3DXVECTOR3 m_MaxAngle;	// 射出する角度の最大値
	D3DXVECTOR3 m_MinAngle;	// 射出する角度の最小値
	float m_Speed;			// 速度
public:
	//===========================================================================
	// set,get
	//===========================================================================

	// -- 角度の最大 --
	void SetMaxAngle(D3DXVECTOR3 angle) { m_MaxAngle = angle; }
	D3DXVECTOR3 GetMaxAngle() { return m_MaxAngle; }

	// -- 角度の最小 --
	void SetMinAngle(D3DXVECTOR3 angle) { m_MinAngle = angle; }
	D3DXVECTOR3 GetMinAngle() { return m_MinAngle; }
};

//========================================================================================================================
// コンストラクタ
//========================================================================================================================
CParticle::CParticle()
{
}

//========================================================================================================================
// デストラクタ
//========================================================================================================================
CParticle::~CParticle()
{
}

//========================================================================================================================
// 初期設定
//========================================================================================================================
HRESULT CParticle::Init()
{
	CEffect::Init();
	return S_OK;
}

//========================================================================================================================
// 終了処理
//========================================================================================================================
void CParticle::Uninit()
{
	CEffect::Uninit();
}

//========================================================================================================================
// 更新処理
//========================================================================================================================
void CParticle::Update()
{
	CEffect::Update();
}

//========================================================================================================================
// 描画処理
//========================================================================================================================
void CParticle::Draw()
{
	CEffect::Draw();
}

//========================================================================================================================
// 生成処理
//========================================================================================================================
CParticle* CParticle::Create()
{
	CParticle* pParticle = new CParticle;
	pParticle->Init();

	return pParticle;
}

#endif // !PARTICLE_H_