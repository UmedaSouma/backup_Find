#include "particle_manager.h"
#include "particle.h"

//===========================================================================================================
// コンストラクタ
//===========================================================================================================
CParticleManager::CParticleManager() :
	m_Isloop(false),
	m_Num(0)
{
}

//===========================================================================================================
// デストラクタ
//===========================================================================================================
CParticleManager::~CParticleManager()
{
}

//===========================================================================================================
// 更新処理
//===========================================================================================================
void CParticleManager::Update()
{
	if (m_Isloop)
	{
		for (int i = 0; i < m_Num; i++)
		{
			CParticle::Create();
		}
	}
}

//===========================================================================================================
// パーティクルを出す
//===========================================================================================================
void CParticleManager::SetParticle(bool loop, int num)
{
	m_Isloop = loop;
	m_Num = num;
}