#include "number.h"
#include "manager.h"

//========================================================================================================================
// コンストラクタ
//========================================================================================================================
CNumber::CNumber() :
	m_TypeNum(FONT_DOT_WBW),
	m_Number(0)
{
}

//========================================================================================================================
// デストラクタ
//========================================================================================================================
CNumber::~CNumber()
{
}

//========================================================================================================================
// 初期設定
//========================================================================================================================
HRESULT CNumber::Init()
{
	SetPos({ SCREEN_WIDTH * 0.5f,SCREEN_HEIGHT * 0.5f,0.0f });
	SetSize({ 40,40,50 });

	int Idx = 0;
	Idx = CManager::GetTexture()->Regist(m_NumberPass[m_TypeNum]);
	BindTexture(CManager::GetTexture()->GetAddress(Idx));

	//SetTexSplit({ 1000,1 });
	//SetAnimeInterval(1);

	// テクスチャ分割
	SetTexSpritInfo({
		{0.0f,0.0f},{0.1f,0.0f},
		{0.0f,1.0f},{0.1f,1.0f}
		});

	CObject2D::Init();
	return S_OK;
}

//========================================================================================================================
// 終了処理
//========================================================================================================================
void CNumber::Uninit()
{
	CObject2D::Uninit();
}

//========================================================================================================================
// 更新処理
//========================================================================================================================
void CNumber::Update()
{
	// テクスチャ分割
	SetTexSpritInfo({
		{0.1f*m_Number,0.0f},{0.1f * (m_Number+1),0.0f},
		{0.1f*m_Number,1.0f},{0.1f * (m_Number+1),1.0f}
		});

	CObject2D::Update();
}

//========================================================================================================================
// 描画処理
//========================================================================================================================
void CNumber::Draw()
{
	CObject2D::Draw();
}

//========================================================================================================================
// 生成処理
//========================================================================================================================
CNumber* CNumber::Create(FONT_TYPE type)
{
	CNumber* pNumber = new CNumber;
	pNumber->m_TypeNum = type;
	pNumber->Init();

	return pNumber;
}