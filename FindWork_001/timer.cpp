#include "timer.h"

//===========================================================================================================
// コンストラクタ
//===========================================================================================================
CTimer::CTimer()
{
	m_Timer = 0;
	m_bPlay = false;
	m_pDisNum[TIME_SEC] = nullptr;
	m_pDisNum[TIME_MIN] = nullptr;

	// 時間情報の初期化
	m_TimeInfo.sec = 0;
	m_TimeInfo.min = 0;
	m_TimeInfo.hor = 0;
}

//===========================================================================================================
// デストラクタ
//===========================================================================================================
CTimer::~CTimer()
{
}

//===========================================================================================================
// 初期化処理
//===========================================================================================================
void CTimer::Init()
{
	D3DXVECTOR3 pos = { 1200.0f,50.0f,0.0f };
	float Number_Interval = 150.0f;

	for (int i = 0; i < TIME_MAX; i++)
	{
		// 表示する数値の生成
		m_pDisNum[i] = CDisplayNumber::Create(
			pos,							/* 位置 */
			0,								/* 設定する数値 */
			CDisplayNumber::DIGID_TEN,		/* 桁数 */
			CNumber::FONT_DOT_WBW			/* フォント */
		);

		// 秒と分で間隔を開ける
		pos.x -= Number_Interval;
	}

	Play();
}

//===========================================================================================================
// 終了処理
//===========================================================================================================
void CTimer::Uninit()
{
	// DisNum ポインタの削除
	for (int i = 0; i < TIME_MAX; i++)
	{
		if (m_pDisNum[i] != nullptr)
		{
			m_pDisNum[i]->Uninit();
			//delete m_pDisNum[i];
			m_pDisNum[i] = nullptr;
		}	
	}

	delete this;
}

//===========================================================================================================
// 更新処理
//===========================================================================================================
void CTimer::Update()
{
	if (m_bPlay)
	{// 再生中の時
		m_Timer++;	// フレームカウントを進める
	}

	// タイム表示
	m_pDisNum[TIME_SEC]->Update(m_TimeInfo.sec);
	m_pDisNum[TIME_MIN]->Update(m_TimeInfo.min);

	// 時間計算
	TimeCalculation();
}

void CTimer::Draw()
{
}

//===========================================================================================================
// 再生
//===========================================================================================================
void CTimer::Play()
{
	m_bPlay = true;
}

//===========================================================================================================
// 一時停止
//===========================================================================================================
void CTimer::Pause()
{
	m_bPlay = false;
}

//===========================================================================================================
// リセット
//===========================================================================================================
void CTimer::Reset()
{
	m_Timer = 0;
}

//===========================================================================================================
// 停止
//===========================================================================================================
void CTimer::Stop()
{
	Pause();
	Reset();
}

