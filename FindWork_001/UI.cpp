#include "UI.h"
#include "manager.h"

//========================================================================================================================
// コンストラクタ
//========================================================================================================================
CUI::CUI(int nPriority) :CObject2D(nPriority)
{
}

//========================================================================================================================
// デストラクタ
//========================================================================================================================
CUI::~CUI()
{
}

//========================================================================================================================
// 初期設定
//========================================================================================================================
HRESULT CUI::Init()
{
	CObject2D::Init();
	return S_OK;
}

//========================================================================================================================
// 終了処理
//========================================================================================================================
void CUI::Uninit()
{
	CObject2D::Uninit();
}

//========================================================================================================================
// 更新処理
//========================================================================================================================
void CUI::Update()
{
	CObject2D::Update();
}

//========================================================================================================================
// 描画処理
//========================================================================================================================
void CUI::Draw()
{
	CObject2D::Draw();
}

//========================================================================================================================
// 生成処理
//========================================================================================================================
CUI* CUI::Create(D3DXVECTOR3 pos, D3DXVECTOR3 size, const char* texpass)
{
	CUI* pObj = new CUI;
	pObj->SetPos(pos);
	pObj->SetSize(size);

	// テクスチャの設定
	int Idx = 0;
	Idx = CManager::GetTexture()->Regist(texpass);
	pObj->BindTexture(CManager::GetTexture()->GetAddress(Idx));

	pObj->Init();

	return pObj;
}