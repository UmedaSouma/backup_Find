#include "course_point.h"
#include "search.h"
#include "car_player.h"
#include "collision.h"

//========================================================================================================================
// コンストラクタ
//========================================================================================================================
CCoursePoint::CCoursePoint() :
	m_nIdxPoint(-1),
	m_bPassPoint(false)
{
}

//========================================================================================================================
// デストラクタ
//========================================================================================================================
CCoursePoint::~CCoursePoint()
{
}

//========================================================================================================================
// 初期設定
//========================================================================================================================
HRESULT CCoursePoint::Init()
{
	SetModel("data\\MODEL\\course_point_000.x");
#ifdef _DEBUG
#endif // !_DEBUG
	SetType(CObject::POINT);
	CModel::Init();

	return S_OK;
}

//========================================================================================================================
// 終了処理
//========================================================================================================================
void CCoursePoint::Uninit()
{
	CModel::Uninit();
}

//========================================================================================================================
// 更新処理
//========================================================================================================================
void CCoursePoint::Update()
{
	PassPointUpdate();

	CModel::Update();
}

//========================================================================================================================
// 描画処理
//========================================================================================================================
void CCoursePoint::Draw()
{
	CModel::Draw();
}

//===========================================================================================================
// ポイントを通る
//===========================================================================================================
void CCoursePoint::PassPointUpdate()
{
	CCarPlayer* player = nullptr;
	player = CSearch::SearchObject(player, CObject::CAR_PLAYER);

	if (player == nullptr)
	{
		return;
	}

	if (CCollision::SphereTrigger(player->GetPos(), 20.0f, GetPos(), 100.0f))
	{
		m_bPassPoint = true;
	}
}

//========================================================================================================================
// 生成処理
//========================================================================================================================
CCoursePoint* CCoursePoint::Create(int Idx,D3DXVECTOR3 pos, D3DXVECTOR3 rot)
{
	CCoursePoint* pCoursePoint = new CCoursePoint;

	// インデックスで順番を設定
	pCoursePoint->m_nIdxPoint = Idx;
	pCoursePoint->SetPos(pos);
	pCoursePoint->SetRot(rot);

	pCoursePoint->Init();

	return pCoursePoint;
}